function config(raw = {}) {
  if (!themes.some(t => t.id === raw.theme)) throw new Error('Unknown theme');
  if (!Object.hasOwn(accents, raw.accent)) throw new Error('Unknown accent');
  if (!symbols.includes(raw.symbol)) throw new Error('Unknown symbol');
  if (!scenarios.includes(raw.scenario)) throw new Error('Unknown scenario');
  return { theme: raw.theme, accent: raw.accent, symbol: raw.symbol, scenario: raw.scenario,
    git: raw.git !== false, user: raw.user !== false, multiline: raw.multiline !== false,
    cols: Math.max(40, Math.min(180, Number(raw.cols) || 100)), rows: 24 };
}

function themeSource(c) {
  const color = accents[c.accent] || 'green';
  let code;
  if (c.theme === 'studio') {
    const identity = c.user ? '%F{242}%n@%m%f ' : '';
    const branch = c.git ? ' $(git_prompt_info)' : '';
    const first = `${identity}%F{${color}}%~%f${branch}`;
    const end = `%(?.%F{${color}}.%F{red})${c.symbol}%f `;
    code = `# Studio — generated by Promptlab\n# Requires Oh My Zsh (git helpers).\nZSH_THEME_GIT_PROMPT_PREFIX='%F{242}on %F{magenta}'\nZSH_THEME_GIT_PROMPT_SUFFIX='%f'\nZSH_THEME_GIT_PROMPT_DIRTY='%F{yellow} *%f'\nZSH_THEME_GIT_PROMPT_CLEAN=''\nPROMPT='${first}${c.multiline ? '\n' : ' '}${end}'\nRPROMPT='%(?..%F{red}exit %?%f)'\n`;
  } else {
    code = readFileSync(path.join(vendor, 'themes', `${c.theme}.zsh-theme`), 'utf8');
    if (c.accent !== 'original') {
      code = code.replace(/(fg(?:_bold)?\[)(green|cyan|blue|magenta)(\])/g, `$1${color}$3`)
        .replace(/%F\{(?:green|cyan|blue|magenta)\}/g, `%F{${color}}`)
        .replace(/(prompt_segment\s+)(?:blue|green|cyan|magenta)(\s)/g, `$1${color}$2`);
      // af-magic uses the 256-color table for its path rather than named colors.
      if (c.theme === 'af-magic') {
        const idx = { green: '078', cyan: '081', magenta: '141', yellow: '214', blue: '075' }[color];
        code = code.replaceAll('${FG[032]}', '${FG[' + idx + ']}');
      }
      if (c.theme === 'agnoster') code = `AGNOSTER_DIR_BG=${color}\nAGNOSTER_VENV_BG=${color}\n` + code;
    }
    if (c.theme === 'robbyrussell') code = code.replaceAll('➜', c.symbol);
    if (!c.git) code += '\n# Promptlab override: hide Git segments\nfunction git_prompt_info() { :; }\nfunction git_prompt_status() { :; }\n' + (c.theme === 'agnoster' ? 'function prompt_git() { :; }\n' : '') + (c.theme === 'avit' ? 'function _git_time_since_commit() { :; }\n' : '');
    code = `# Customized with Promptlab\n# Base: ohmyzsh/ohmyzsh @ ${sha}\n# Original source: https://github.com/ohmyzsh/ohmyzsh/blob/${sha}/themes/${c.theme}.zsh-theme\n# Requires Oh My Zsh. Upstream MIT license is included in vendor/ohmyzsh/LICENSE.txt.\n\n${code}`;
  }
  return code;
}

