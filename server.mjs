const children = new Set();
function worker(c, mode) {
  const dir = mkdtempSync(path.join(tmpdir(), 'promptlab-job-'));
  writeFileSync(path.join(dir, 'theme.zsh-theme'), themeSource(c));
  writeFileSync(path.join(dir, 'job.json'), JSON.stringify({ ...c, vendor, dir, mode }));
  const p = spawn('python3', ['-u', path.join(root, 'worker.py'), path.join(dir, 'job.json')], { stdio: ['pipe', 'pipe', 'pipe'] });
  children.add(p);
  const timer = setTimeout(() => p.kill('SIGTERM'), mode === 'live' ? 180000 : 14000);
  p.once('close', () => { clearTimeout(timer); children.delete(p); rmSync(dir, { recursive: true, force: true }); });
  return p;
}
const cache = new Map();
let snapshots = 0;
const snapshotWaiters = [];
function releaseSnapshot() { if (snapshotWaiters.length) snapshotWaiters.shift()(); else snapshots--; }
app.post('/api/render', async (req, res) => {
  let c;
  try { c = config(req.body); } catch (e) { return res.status(400).json({ error: e.message }); }
  const key = JSON.stringify(c);
  if (cache.has(key)) return res.json({ output: cache.get(key) });
  if (snapshotWaiters.length >= 24) return res.status(429).json({ error: '预览繁忙，请稍后重试' });
  if (snapshots >= 3) await new Promise(resolve => snapshotWaiters.push(resolve));
  else snapshots++;
  if (res.destroyed) { releaseSnapshot(); return; }
  const p = worker(c, 'snapshot');
  let data = '', errors = '';
  p.stdout.on('data', b => { data += b; if (data.length > 250000) p.kill('SIGTERM'); });
  p.stderr.on('data', b => { errors += b; });
  res.on('close', () => { if (!res.writableEnded) p.kill('SIGTERM'); });
  p.once('close', code => {
    releaseSnapshot();
    if (res.destroyed) return;
    if (code !== 0) return res.status(500).json({ error: errors.slice(0, 500) || 'Preview worker stopped' });
    if (cache.size > 150) cache.delete(cache.keys().next().value);
    cache.set(key, data); res.json({ output: data });
  });
});

const wss = new WebSocketServer({ noServer: true, maxPayload: 4096 });
server.on('upgrade', (req, socket, head) => {
  if (!req.url.startsWith('/api/terminal')) return;
  if (!origins.has(req.headers.origin) || !new Set([`127.0.0.1:${port}`, `localhost:${port}`]).has(req.headers.host) || wss.clients.size >= 3) return socket.destroy();
  wss.handleUpgrade(req, socket, head, ws => wss.emit('connection', ws));
});
wss.on('connection', ws => {
  let p, bytes = 0;
  const send = obj => { if (ws.readyState === 1) ws.send(JSON.stringify(obj)); };
  ws.on('message', raw => {
    try {
      const message = JSON.parse(raw);
      if (message.type === 'start' && !p) {
        p = worker(config(message.config), 'live');
        let pending = '';
        p.stdout.on('data', b => {
          bytes += b.length;
          if (bytes > 750000) { p.kill('SIGTERM'); return; }
          pending += b.toString();
          let line;
          while ((line = pending.indexOf('\n')) !== -1) {
            const entry = pending.slice(0, line); pending = pending.slice(line + 1);
            try { send(JSON.parse(entry)); } catch { /* incomplete worker event */ }
          }
        });
        p.stderr.on('data', b => send({ type: 'error', message: b.toString().slice(0, 300) }));
        p.on('close', () => { send({ type: 'closed' }); ws.close(); });
      } else if (message.type === 'command' && p && commands.has(message.command)) {
        p.stdin.write(JSON.stringify({ command: message.command }) + '\n');
      } else if (message.type === 'resize' && p) {
        p.stdin.write(JSON.stringify({ cols: Math.max(40, Math.min(180, Number(message.cols) || 100)), rows: 24 }) + '\n');
      } else { send({ type: 'error', message: 'POC 仅支持下方列出的演示命令。试试 git status、pwd 或 false。' }); }
    } catch (e) { send({ type: 'error', message: e.message }); }
  });
  ws.on('close', () => p?.kill('SIGTERM'));
});
